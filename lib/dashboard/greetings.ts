import type { AddressForm } from '@/lib/profile/local'

// Маленький словарь приветствий: время суток × форма обращения. Род/число-
// аффирмативные варианты (она/он/они) — единственное место с такими маркерами
// в UI; нейтраль — без них (повелит. / средний род / согласование с
// существительным, не с человеком). Массивы — чтобы легко расширять; выбор
// ротацией по дню месяца (стабильно в течение дня, меняется назавтра).

type Bucket = 'morning' | 'day' | 'evening'

function bucketFor(date: Date): Bucket {
  const h = date.getHours()
  if (h >= 5 && h < 12) return 'morning'
  if (h >= 12 && h < 18) return 'day'
  return 'evening'
}

const GREETINGS: Record<Bucket, Record<AddressForm, string[]>> = {
  morning: {
    she: ['Надеюсь, ты хорошо спала', 'Пусть утро будет мягким'],
    he: ['Надеюсь, ты хорошо спал', 'Пусть утро будет мягким'],
    they: ['Надеюсь, ты хорошо спали', 'Пусть утро будет мягким'],
    neutral: ['Доброе утро ✦', 'Пусть утро будет мягким'],
  },
  day: {
    she: ['Надеюсь, ты не устала', 'Как проходит день?'],
    he: ['Надеюсь, ты не устал', 'Как проходит день?'],
    they: ['Надеюсь, ты не устали', 'Как проходит день?'],
    neutral: ['Как проходит день?', 'Пусть день будет спокойным'],
  },
  evening: {
    she: ['Надеюсь, ты хорошо провела день', 'Время выдохнуть'],
    he: ['Надеюсь, ты хорошо провёл день', 'Время выдохнуть'],
    they: ['Надеюсь, ты хорошо провели день', 'Время выдохнуть'],
    neutral: ['Надеюсь, день прошёл хорошо', 'Время выдохнуть'],
  },
}

export function pickGreeting(form: AddressForm, date: Date = new Date()): string {
  const arr = GREETINGS[bucketFor(date)][form]
  return arr[date.getDate() % arr.length]
}
