import type { IntakeStatus } from './queries'

/**
 * Статистика регулярности приёмов за диапазон.
 *
 * ЗАГОТОВКА ПОД ЗАХОД 3 — UI её пока не вызывает.
 *
 * --- Про приватность (важно, это влияет на сигнатуру) ---
 *
 * Функция принимает НЕ IntakeSlot, а минимальную форму {status, scheduled_at}.
 * Это сделано нарочно: так она структурно не может дотянуться до name,
 * dose_amount и прочих полей препарата. Когда поля medications уедут в E2E
 * (они кандидаты, см. CLAUDE.md), сюда прилетит ровно ноль изменений —
 * статус и время приёма шифроваться не планируются, они и так нужны серверу
 * для напоминалок.
 *
 * Отсюда же следует, чего здесь НЕТ и не должно появиться: разбивки «сколько
 * эстрогена принято», группировки по названию, сумм по дозам. Любая такая
 * метрика завязала бы Историю на плейнтекст названий препаратов. Решение
 * зафиксировано 2026-08-03, обсуждать отдельно.
 *
 * --- Про подсчёт ---
 *
 * Считаем на клиенте функции, а не агрегатом в Postgres, потому что Истории
 * ряды всё равно нужны для ленты — второй запрос был бы лишним round-trip'ом
 * ради тех же чисел. Если диапазоны вырастут до тысяч рядов, это место
 * честно переписать в count(*) group by status.
 */

/** Минимум, нужный для подсчёта. Намеренно уже, чем IntakeSlot. */
export interface CountableSlot {
  status: IntakeStatus
  scheduled_at: string // ISO UTC
}

export interface IntakeStats {
  /** Отмечено принятым (включая отмеченное задним числом). */
  taken: number
  /** Пропущено: день юзера кончился, слот так и остался неотмеченным. */
  missed: number
  /** Осознанно пропущено самим юзером. */
  skipped: number
  /**
   * Время слота прошло, но он ещё upcoming — то есть сегодняшний неотмеченный.
   * Развёртка mark_missed_intakes переведёт его в missed только когда у юзера
   * кончится день, так что днём такие слоты нормальны и провалом НЕ считаются:
   * их ещё можно отметить.
   */
  pending: number
  /** Время слота ещё не наступило. */
  upcoming: number
  /**
   * Знаменатель для «принято X из Y» — прошедшие и уже решённые слоты
   * (taken + missed + skipped). pending сюда НЕ входит: засчитывать провалом
   * то, что юзер ещё может отметить сегодня, значит показывать цифру, которая
   * скачет в течение дня.
   */
  due: number
  /**
   * Регулярность = taken / (taken + missed). Доля 0..1, форматирует UI.
   * null когда знаменатель нулевой (нечего показывать — не 0%, это разные вещи).
   *
   * skipped в знаменателе НЕТ сознательно: «Пропустить» в интерфейсе подано
   * нейтрально, без негативной окраски (см. комментарий в slot-card.tsx), и
   * считать осознанный пропуск неудачей противоречило бы этому тону.
   * Показываем его отдельным числом.
   */
  adherence: number | null
}

/**
 * Посчитать статистику по набору слотов.
 *
 * @param slots — слоты диапазона; порядок не важен.
 * @param now — момент «сейчас», инъектируется для тестов и предсказуемости
 *              рендера (за один проход рендера должен быть один now).
 */
export function computeIntakeStats(
  slots: readonly CountableSlot[],
  now: Date = new Date(),
): IntakeStats {
  const nowMs = now.getTime()

  let taken = 0
  let missed = 0
  let skipped = 0
  let pending = 0
  let upcoming = 0

  for (const slot of slots) {
    switch (slot.status) {
      case 'taken':
        taken += 1
        break
      case 'missed':
        missed += 1
        break
      case 'skipped':
        skipped += 1
        break
      case 'upcoming':
        // Единственное место, где смотрим на время: делим неотмеченные на
        // «время прошло, ещё можно успеть» и «ещё не наступило».
        if (new Date(slot.scheduled_at).getTime() < nowMs) pending += 1
        else upcoming += 1
        break
    }
  }

  const due = taken + missed + skipped
  const adherenceBase = taken + missed

  return {
    taken,
    missed,
    skipped,
    pending,
    upcoming,
    due,
    adherence: adherenceBase === 0 ? null : taken / adherenceBase,
  }
}
