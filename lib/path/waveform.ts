// Псевдослучайная «волна» голосовой записи: высоты штрихов, выведенные из id
// записи. Общая для превью в ленте и полного просмотра — иначе одна и та же
// запись рисовалась бы двумя разными волнами.
//
// Почему не настоящая амплитуда: файл зашифрован и качается лениво, а рисовать
// волну надо сразу. Форма стабильна между рендерами (детерминирована по id) —
// глазу этого достаточно.

export function barsFromSeed(seed: string, count: number, min = 5, max = 18): number[] {
  // FNV-1a: дешёвый хеш строки в число, дальше xorshift для потока значений.
  let h = 2166136261
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  const out: number[] = []
  for (let i = 0; i < count; i++) {
    h ^= h << 13
    h ^= h >>> 17
    h ^= h << 5
    out.push(min + Math.round((Math.abs(h % 100) / 100) * (max - min)))
  }
  return out
}
