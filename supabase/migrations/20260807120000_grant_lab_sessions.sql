-- ============================================================================
-- GRANT для роли authenticated и service_role на lab_sessions
-- ============================================================================
--
-- ⚠️ В ТЕКУЩЕЙ БАЗЕ УЖЕ ПРИМЕНЁН РУКАМИ (2026-08-07). Этот файл — для истории
-- и для пересоздания базы с нуля. Повторный прогон безвреден: GRANT
-- идемпотентен, повторная выдача тех же прав ничего не меняет и не падает.
--
-- Зачем файл, если в базе всё есть: чтобы схема в репозитории совпадала с
-- реальной. Иначе при пересоздании проекта таблица приедет без привилегий,
-- и мы третий раз наступим на те же грабли.
--
-- ----------------------------------------------------------------------------
-- Почему это вообще нужно отдельным шагом
-- ----------------------------------------------------------------------------
-- Таблицы, созданные raw SQL, НЕ получают привилегий ролям автоматически —
-- Supabase делает это только при создании через Table Editor. Проект уже
-- дважды на этом обжигался, оба раза отдельными фиксами:
--   20260526120000_grant_authenticated.sql  — profiles, medications, intake_events
--   20260613120000_grant_service_role.sql   — они же для service_role
-- С тех пор каждая миграция, создающая таблицу, выдаёт права явно
-- (push_subscriptions, path_entries, lab_results). Миграция lab_sessions
-- (20260805120000) этого не сделала — данный файл закрывает пропуск.
--
-- Отдельно про то, почему без этого ломается не только сама lab_sessions:
-- политики INSERT/UPDATE на lab_results содержат
--   exists (select 1 from public.lab_sessions ...)
-- а Postgres проверяет привилегии на ВСЕ таблицы, которые задевает стейтмент,
-- включая пришедшие из выражения RLS-политики, и делает это на старте
-- исполнения — до значений строк. Без GRANT любая вставка или правка анализа
-- отбивалась бы с «permission denied for table lab_sessions», даже когда
-- session_id пуст.
--
-- Обход RLS и привилегии на таблицу — независимые механизмы: service_role не
-- фильтруется политиками, но без GRANT не может даже открыть таблицу.
-- Выдаём ей полный CRUD, как и остальным таблицам, чтобы новый cron-сценарий
-- не требовал очередной GRANT-миграции.
--
-- ----------------------------------------------------------------------------
-- КАК ПРИМЕНИТЬ (Supabase CLI не настроен — накатываем руками)
-- ----------------------------------------------------------------------------
-- Только при пересоздании базы: Dashboard → SQL Editor → New query →
-- вставить → Run. В текущей базе прогонять не требуется, уже применено.
--
-- Проверка:
--   select grantee, privilege_type
--   from information_schema.role_table_grants
--   where table_schema = 'public' and table_name = 'lab_sessions'
--   order by grantee, privilege_type;
--   -- ждём по четыре строки (DELETE/INSERT/SELECT/UPDATE) на authenticated
--   -- и на service_role
--
-- Откат (не нужен в норме):
--   revoke all on public.lab_sessions from authenticated;
--   revoke all on public.lab_sessions from service_role;
-- ============================================================================

grant select, insert, update, delete on public.lab_sessions to authenticated;
grant select, insert, update, delete on public.lab_sessions to service_role;

