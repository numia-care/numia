-- ============================================================================
-- E2E-синхронизация профиля: имя + форма обращения как шифроблоб в profiles
-- ============================================================================
--
-- Решение (зафиксировано 2026-07-15). Профиль (имя для приветствия и форма
-- обращения) жил ТОЛЬКО в localStorage — терялся при переустановке PWA и не
-- синкался между устройствами. Переносим на сервер, но НЕ открытым текстом:
--
--   • Контент шифруется на устройстве тем же DEK, что дневник и «Путь»
--     (lib/crypto/envelope.ts, encryptText). В колонке — base64(iv ‖ ct),
--     как в path_entries.note_ciphertext: IV упакован внутри, отдельная
--     колонка не нужна.
--   • Сервер и команда прочитать НЕ могут: имя — личное (правило CLAUDE.md
--     «не требуем настоящее имя» и профильная память «личного в profiles —
--     никогда» остаются в силе: на сервере лежит нечитаемый шифроблок).
--   • Зачем серверу вообще эта колонка: кросс-девайс и переустановка PWA —
--     тот же аргумент, что для dek_wrapped_recovery. localStorage остаётся
--     локальным КЭШЕМ для мгновенного приветствия, источник правды — здесь.
--
-- NULL = профиль ещё не поднимали (или юзер до этой версии). Конфликтов не
-- боимся: last-write-wins, это имя и одна опция.
--
-- Как применить:
-- Supabase Dashboard → SQL Editor → New query → вставить → Run.
-- ============================================================================

alter table public.profiles
  add column if not exists profile_ciphertext text;

comment on column public.profiles.profile_ciphertext is
  'E2E-шифроблоб профиля (имя + форма обращения): base64(iv‖ct) под DEK юзера. Сервер расшифровать не может.';

