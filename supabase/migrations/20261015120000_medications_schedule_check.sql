-- ----------------------------------------------------------------------------
-- РАЗДЕЛ 3. Констрейнт  ← выполнить третьим, ТОЛЬКО если раздел 2 дал 0
-- ----------------------------------------------------------------------------

-- ВАРИАНТ А (нормальный путь, битых строк нет).
-- Проверяет все существующие строки сразу. Упадёт, если хоть одна битая.
alter table public.medications
  add constraint medications_schedule_valid
  check (public.is_valid_medication_schedule(schedule));

-- ВАРИАНТ Б (если битые строки ЕСТЬ и нужно остановить появление новых,
-- пока разбираешься со старыми). Закомментирован — раскомментировать вместо
-- варианта А, а вариант А тогда НЕ выполнять.
--
-- NOT VALID: существующие строки не проверяются, но любая вставка и любое
-- обновление — проверяются. То есть новый мусор не появится, а старый
-- останется до починки. Побочный эффект, скорее полезный: правка битого
-- препарата в интерфейсе теперь не сохранится, пока расписание не станет
-- валидным.
--
--   alter table public.medications
--     add constraint medications_schedule_valid
--     check (public.is_valid_medication_schedule(schedule)) not valid;
--
-- После починки старых строк — дочистить и включить проверку полностью:
