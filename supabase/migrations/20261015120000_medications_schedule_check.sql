-- ----------------------------------------------------------------------------
-- РАЗДЕЛ 1. Функция проверки  ← выполнить первым, отдельно
-- ----------------------------------------------------------------------------
-- IMMUTABLE: результат зависит только от аргумента. Это обязательно для
-- использования в CHECK (иначе Postgres не сможет полагаться на констрейнт
-- при дампе/восстановлении).
--
-- search_path = '' — как в остальных функциях проекта. Всё используемое
-- (jsonb_typeof, jsonb_array_elements, операторы ->, ->>, #>>, !~) живёт в
-- pg_catalog, который в пути поиска всегда.

create or replace function public.is_valid_medication_schedule(s jsonb)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
declare
  -- Тот же формат, что TIME_REGEX в lib/tracker/schedule.ts: часы и минуты
  -- строго двузначные. '9:00' без ведущего нуля — невалидно, и это не
  -- придирка: именно оно давало Invalid Date, выглядя безобидно.
  time_re constant text := '^([01][0-9]|2[0-3]):[0-5][0-9]$';
  date_re constant text := '^[0-9]{4}-[0-9]{2}-[0-9]{2}$';
  kind    text;
  n       integer;
  -- НЕ `every`: every() — агрегатная функция Postgres, и переменная с таким
  -- именем ломала бы разбор выражения ниже.
  days    numeric;
begin
  -- Колонка NOT NULL, но проверяем: CHECK на NULL-результате пропустил бы
  -- строку (NULL трактуется как «не нарушено»).
  if s is null then
    return false;
  end if;
  if jsonb_typeof(s) is distinct from 'object' then
    return false;
  end if;

  kind := s->>'kind';

  -- ── daily ────────────────────────────────────────────────────────────────
  if kind = 'daily' then
    -- IS DISTINCT FROM, а не <>: при отсутствующем ключе s->'times' даёт NULL,
    -- jsonb_typeof(NULL) тоже NULL, и `NULL <> 'array'` было бы NULL — то есть
    -- IF не сработал бы, и строка без times прошла бы дальше.
    if jsonb_typeof(s->'times') is distinct from 'array' then
      return false;
    end if;

    n := jsonb_array_length(s->'times');
    if n < 1 or n > 12 then
      return false;
    end if;

    -- Каждый элемент — строка нужного формата.
    if exists (
      select 1
      from jsonb_array_elements(s->'times') as e(v)
      where jsonb_typeof(e.v) is distinct from 'string'
         or (e.v #>> '{}') !~ time_re
    ) then
      return false;
    end if;

    -- Без повторов.
    if (select count(distinct e.v) from jsonb_array_elements(s->'times') as e(v)) <> n then
      return false;
    end if;

    return true;
  end if;

  -- ── interval ─────────────────────────────────────────────────────────────
  if kind = 'interval' then
    if jsonb_typeof(s->'every_days') is distinct from 'number' then
      return false;
    end if;
    days := (s->>'every_days')::numeric;
    -- trunc отсекает дробные. Отдельно ловить Infinity не нужно: jsonb не
    -- умеет его хранить (в JSON такого числа нет), в отличие от JS, где
    -- Infinity проходил прежнюю проверку `typeof === 'number' && >= 1`.
    if days <> trunc(days) or days < 1 or days > 180 then
      return false;
    end if;

    if jsonb_typeof(s->'time') is distinct from 'string' then
      return false;
    end if;
    if (s->>'time') !~ time_re then
      return false;
    end if;

    if jsonb_typeof(s->'anchor_date') is distinct from 'string' then
      return false;
    end if;
    -- Только ФОРМАТ, как и в zod. Календарную существование даты не проверяем
    -- намеренно — чтобы констрейнт не был строже клиента. Про '2026-13-45'
    -- см. примечание в конце файла.
    if (s->>'anchor_date') !~ date_re then
      return false;
    end if;

    return true;
  end if;

  -- kind не daily и не interval (или ключа нет вовсе).
  return false;
end;
$$;

