-- convalidated = true. Диагностика перед применением: 0 негодных строк из 50
-- препаратов. Дымовые тесты пройдены — негодное расписание отклоняется,
-- валидное проходит.
--
-- Зачем. Форму расписания проверял только zod (lib/tracker/schedule.ts), то
-- есть рантайм Node. В самой БД инварианта не было: колонка объявлена просто
-- как `schedule jsonb not null`, без CHECK. Проверка, живущая в одном клиенте,
-- не держит остальных — ни веб, ни будущий iOS, ни прямой запрос в PostgREST.
--
-- Цена отсутствия инварианта оказалась несоразмерной форме ошибки: ночная
-- генерация слотов (supabase/functions/generate-upcoming) не переживала
-- неожидаемое значение и не создавала слоты НИ ОДНОМУ пользователю — пуши
-- переставали приходить всем. Само не восстанавливалось.
--
-- Та функция уже укреплена (строгий parseSchedule + try/catch вокруг цикла по
-- препаратам), так что отказа в обслуживании больше нет. Но защита в одном
-- пути кода — не инвариант: он должен жить там, где данные. Эта миграция и
-- ставит его на место, закрывая всех клиентов разом.
--
-- ----------------------------------------------------------------------------
-- ПОЧЕМУ ФУНКЦИЯ, А НЕ ВЫРАЖЕНИЕ ПРЯМО В CHECK
-- ----------------------------------------------------------------------------
-- CHECK в Postgres не может содержать подзапросы. А проверка «каждый элемент
-- times — строка формата HH:MM» без подзапроса не выражается:
-- jsonb_array_elements — функция, возвращающая множество. Поэтому логика
-- вынесена в IMMUTABLE-функцию, а CHECK её вызывает.
--
-- Побочная выгода: проверить данные ПЕРЕД добавлением констрейнта можно той
-- же самой функцией (шаг 2 ниже). Отдельный диагностический запрос разошёлся
-- бы с констрейнтом при любой правке — здесь расходиться нечему.
--
-- plpgsql, а не sql: в plpgsql порядок IF гарантирован. В языке sql порядок
-- вычисления AND не определён, и jsonb_array_length на не-массиве могло бы
-- выполниться раньше проверки типа и упасть.
--
-- ----------------------------------------------------------------------------
-- КАКИЕ ИНВАРИАНТЫ (копия zod-схемы из lib/tracker/schedule.ts)
-- ----------------------------------------------------------------------------
--   daily:    { kind, times }
--             times — массив 1..12 строк, каждая строго HH:MM
--             (двузначные часы 00-23, двузначные минуты 00-59), без повторов.
--             Повторы отдельно: они ломают unique-индекс
--             (medication_id, scheduled_at) при вставке слотов.
--   interval: { kind, every_days, time, anchor_date }
--             every_days — целое 1..180, time — HH:MM,
--             anchor_date — YYYY-MM-DD, все четыре поля обязательны.
--
-- Лишние ключи НЕ запрещены — сознательное решение, см. раздел в конце файла.
--
-- ----------------------------------------------------------------------------
-- КАК ПРИМЕНЯЛАСЬ (Supabase CLI не настроен — накатываем руками)
-- ----------------------------------------------------------------------------
-- На проде этот порядок уже пройден (см. отметку в начале файла). Ниже он
-- оставлен как есть — он понадобится для нового окружения: стейджинга,
-- локального `supabase start`, восстановления из бэкапа.
--
-- Dashboard → SQL Editor → New query. Плейсхолдеров нет.
--
-- ⚠️ НЕ ВСТАВЛЯТЬ ФАЙЛ ЦЕЛИКОМ ОДНИМ ЗАХОДОМ. Шаги 1 и 3 разделены
-- обязательной проверкой: если в базе уже есть негодные строки, ADD CONSTRAINT
-- упадёт, и разбираться придётся посреди половины применённой миграции.
--
--   ШАГ 1. Выполнить только раздел 1 (создание функции). Данные не меняет,
--          ничего не запрещает — безопасно само по себе.
--
--   ШАГ 2. Выполнить проверку из раздела 2. ОБА числа должны быть 0.
--
--   ШАГ 3a. Если 0 — выполнить раздел 3 (ADD CONSTRAINT). Готово.
--
--   ШАГ 3b. Если НЕ 0 — НЕ выполнять раздел 3 в обычном виде. Сначала
--           посмотреть на строки детальным запросом из раздела 2 и решить,
--           что с ними делать (SQL починки — отдельным файлом, в миграцию он
--           не входит намеренно: что считать правильным расписанием вместо
--           битого, решает человек, а не миграция).
--
--           Пока разбираешься, можно сразу остановить появление НОВОГО мусора,
--           добавив констрейнт как NOT VALID (раздел 3, вариант Б): он
--           проверяет вставки и обновления, но не трогает существующие строки.
--           После починки — VALIDATE CONSTRAINT.
--
