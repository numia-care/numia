-- ============================================================================
-- E2E «Путь»: envelope-encryption — серверный якорь recovery-фразы
-- ============================================================================
--
-- Решение (зафиксировано 2026-06-23). Перешли с «ключ прямо из PIN» на
-- envelope encryption (см. lib/crypto/envelope.ts и CLAUDE.md):
--   • контент шифруется случайным DEK (256 бит);
--   • DEK оборачивается дважды — под ключом из PIN и под ключом из 12-словной
--     recovery-фразы (128 бит энтропии).
--
-- ГДЕ ЧТО ЛЕЖИТ (это и определяет схему):
--   • Обёртка под PIN (wrapped_pin) + соль PIN — ТОЛЬКО локально, в IndexedDB.
--     Причина: PIN всего 6 цифр (10^6). Лежи его обёртка на сервере — при
--     утечке/изъятии БД PIN перебирается оффлайн за минуты, и E2E против ровно
--     этой угрозы (CLAUDE.md: госорган, дамп БД) не держит. На сервере слабому
--     секрету не место.
--   • Обёртка под recovery-фразой (dek_wrapped_recovery) + её соль — на сервере,
--     в profiles. 128 бит фразы перебрать нельзя, поэтому это безопасный
--     серверный якорь: с него восстанавливаем доступ на новом устройстве или
--     при забытом PIN. Сама фраза на сервер НЕ попадает — только обёрнутый ею
--     шифротекст DEK. Без фразы сервер DEK не развернёт → контент не прочтёт.
--
-- Это отменяет прошлую миграцию 20260622120100 (pin_crypto_salt на сервере):
-- соль PIN теперь локальная, серверная колонка не нужна — дропаем. Колонка
-- была пустой (код её ещё не писал), потерять нечего.
--
-- Как применить:
-- Supabase Dashboard → SQL Editor → New query → вставить → Run.
-- ============================================================================

-- 1. Серверная колонка соли PIN больше не нужна (соль PIN уехала в IndexedDB).
alter table public.profiles
  drop column if exists pin_crypto_salt;

-- 2. Серверный якорь recovery-фразы.
--    recovery_salt        — соль PBKDF2 для деривации KEK из фразы (не секрет).
--    dek_wrapped_recovery — base64(iv ‖ ciphertext): DEK, обёрнутый ключом из
--                           фразы. Шифротекст — сервер расшифровать не может.
--    Оба nullable: появляются при установке PIN (когда генерится DEK+фраза).
alter table public.profiles
  add column if not exists recovery_salt text,
  add column if not exists dek_wrapped_recovery text;

-- GRANT не нужен: привилегии на profiles выданы на уровне таблицы
-- (20260526/20260613) и покрывают новые колонки. RLS profiles_select_own /
-- profiles_update_own действуют на всю строку — юзер пишет якорь только в свой
-- профиль. Серверная копия безопасна: это шифротекст под 128-битной фразой.
