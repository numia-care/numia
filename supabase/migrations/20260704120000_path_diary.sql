-- ============================================================================
-- Фича «Дневник» — тип записи в «Пути» (настроение + заметка)
-- ============================================================================
--
-- Дневник НЕ отдельная таблица: это entry_type='diary' в той же ленте
-- path_entries. Так лента остаётся единым источником (фото/голос/дневник рядом,
-- одна сортировка по occurred_at, один запрос).
--
-- Граница шифрования (CLAUDE.md, «Уровни шифрования» + раздел «Путь») проведена
-- по полю, ровно как в анализах (lab_results):
--
--   ЧИСЛО настроения (mood, 1–5) — ОТКРЫТО в Postgres под RLS, без E2E. Число
--   не несёт текста о самочувствии и нужно серверу/клиенту для будущих графиков
--   динамики и корреляций (как числа анализов). Защита — RLS user_id=auth.uid(),
--   TLS, encryption-at-rest. Уровень «стандарт».
--
--   ТЕКСТ заметки (note_ciphertext) — E2E, тем же конвейером, что заметка
--   анализов: encryptText(DEK, текст) → base64(iv‖ct), IV внутри. Сервер и
--   команда расшифровать не могут. Здесь человек пишет что угодно своими
--   словами (эмоции, дисфория) — это самое личное, поэтому шифруется.
--
-- Запись дневника = mood (опц.) + заметка (опц.), но ХОТЯ БЫ ОДНО из двух
-- заполнено (CHECK ниже). Пустых записей дневника в ленте быть не должно.
--
-- Как применить (Supabase CLI у нас не настроен):
-- Supabase Dashboard → SQL Editor → New query → вставить весь файл → Run.
-- Проверить: у path_entries появились колонки mood, note_ciphertext; entry_type
-- принимает 'diary'; вставка diary без mood и без заметки падает по CHECK.
--
-- Идемпотентность: alter add column + add constraint упадут при повторном
-- запуске (колонка/констрейнт уже есть) — намеренно, в стиле прошлых миграций.
-- Новых GRANT не нужно: добавленные колонки наследуют привилегии таблицы,
-- уже выданные authenticated/service_role в миграции «Пути».
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. Новые колонки
-- ----------------------------------------------------------------------------

-- Настроение по шкале 1–5. smallint, nullable (запись может быть только текстом).
-- ОТКРЫТО (не шифруется) — см. шапку. Диапазон гарантируется CHECK ниже.
alter table public.path_entries
  add column mood smallint;

-- E2E-текст заметки дневника. base64(iv‖ct) из encryptText — как note_ciphertext
-- в lab_results. nullable (запись может быть только настроением). Сервер не читает.
-- Отдельная колонка (а не общий encrypted_content) — чтобы совпадать с моделью
-- анализов и не смешивать с caption фото/голоса, который лежит в encrypted_content.
alter table public.path_entries
  add column note_ciphertext text;


-- ----------------------------------------------------------------------------
-- 2. entry_type: разрешить 'diary'
-- ----------------------------------------------------------------------------
-- Исходный CHECK создан инлайн без имени — Postgres дал ему имя по конвенции
-- {table}_{column}_check. Снимаем старый, ставим новый с добавленным 'diary'.

alter table public.path_entries
  drop constraint path_entries_entry_type_check;

alter table public.path_entries
  add constraint path_entries_entry_type_check
  check (entry_type in (
    'photo', 'voice', 'note', 'diary', 'lab_result', 'milestone'
  ));


-- ----------------------------------------------------------------------------
-- 3. Целостность дневника
-- ----------------------------------------------------------------------------

-- Настроение в пределах шкалы 1–5 (или отсутствует). Действует на любой ряд:
-- у не-дневниковых записей mood всегда NULL, и NULL проходит проверку.
alter table public.path_entries
  add constraint path_entries_mood_range
  check (mood is null or mood between 1 and 5);

-- Дневниковая запись обязана нести хоть что-то: настроение ИЛИ заметку.
-- Для остальных типов (photo/voice/…) условие всегда истинно (левая часть OR),
-- так что существующие записи не затрагиваются.
alter table public.path_entries
  add constraint path_entries_diary_not_empty
  check (
    entry_type <> 'diary'
    or mood is not null
    or note_ciphertext is not null
  );
