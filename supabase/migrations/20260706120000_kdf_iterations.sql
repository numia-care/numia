-- ============================================================================
-- Версионирование KDF-параметров якоря восстановления (security-аудит, M3)
-- ============================================================================
--
-- Контекст: PBKDF2-итерации подняты 210k → 600k (рекомендация OWASP для
-- PBKDF2-SHA256). Обёртку DEK можно развернуть только теми же параметрами,
-- которыми она создана, поэтому число итераций хранится РЯДОМ с артефактом:
--   • локальный набор (PIN)  → IndexedDB, ключ kdf_iterations (не в БД)
--   • серверный якорь (фраза) → эта колонка
--
-- NULL = якорь создан до версионирования, legacy 210k (клиент интерпретирует
-- сам, см. lib/crypto/vault.ts readRecoveryAnchor). Новые/переписанные якоря
-- получают текущее значение из клиента (writeRecoveryAnchor).
--
-- Это НЕ секрет: число итераций общеизвестно из открытого кода, стойкость
-- держится на самой фразе (128 бит) — колонка просто параметр разворачивания.
--
-- Как применить: Supabase Dashboard → SQL Editor → вставить → Run.
-- Идемпотентность: повторный запуск падёт на add column — намеренно, в стиле
-- остальных миграций.
-- ============================================================================

alter table public.profiles
  add column recovery_kdf_iterations integer
  check (recovery_kdf_iterations is null or recovery_kdf_iterations > 0);

-- GRANT не нужен: новая колонка наследует привилегии таблицы (authenticated
-- уже имеет select/update на profiles), RLS-политики уже стоят по id=auth.uid().
