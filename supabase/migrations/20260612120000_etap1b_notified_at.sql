-- ============================================================================
-- Этап 1b шаг 2: intake_events.notified_at — отметка «напоминание отправлено»
-- ============================================================================
--
-- Зачем: cron send-reminders бежит раз в 5 минут, но реальное время старта
-- функции плавает на секунды (pg_net, холодный старт). Если выбирать события
-- чисто по окну "now .. now+5min", окна соседних запусков не стыкуются —
-- слот на границе либо получит два пуша, либо ни одного. А упавший запуск
-- молча потеряет свои напоминания.
--
-- С notified_at запрос становится идемпотентным:
--   status='upcoming' AND notified_at IS NULL AND scheduled_at < now()+5min
-- Повторный запуск не шлёт дубль (notified_at уже стоит), упавший запуск
-- подхватится следующим (notified_at остался NULL).
--
-- Как применить:
-- Supabase Dashboard → SQL Editor → New query → вставить весь файл → Run.
-- ============================================================================

alter table public.intake_events
  add column notified_at timestamptz;

-- Запрос cron — кросс-юзерный (service_role), существующие индексы ведут
-- с user_id и не помогают. Partial index ровно под условие выборки:
-- «ещё не отправленные напоминания», отсортированные по времени слота.
-- Индекс крошечный — в нём только upcoming-события без отметки.
create index idx_intake_events_notify_pending
  on public.intake_events (scheduled_at)
  where status = 'upcoming' and notified_at is null;
