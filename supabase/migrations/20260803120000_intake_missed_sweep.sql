-- ============================================================================
-- История приёмов, шаг 1: проставление status='missed'
-- ============================================================================
--
-- Что чинит: статус 'missed' есть в CHECK-констрейнте с самого этапа 1a
-- (20260519120000_etap1a_tracker.sql) и рендерится в UI, но НЕ ПРОСТАВЛЯЛСЯ
-- нигде. Неотмеченный слот навсегда оставался 'upcoming': из «Сегодня» он
-- уезжал на следующий день и исчезал с глаз, оставаясь в базе. Ни истории,
-- ни статистики регулярности на таких данных построить нельзя.
--
-- Правило (решение 2026-08-03): слот становится 'missed', когда В ТАЙМЗОНЕ
-- ЮЗЕРА наступил следующий календарный день, а слот всё ещё 'upcoming'.
-- Не фиксированные N часов — именно «день юзера кончился». Поэтому нужен
-- джойн с profiles.timezone: 'вчера' у юзера в Мадриде и в Владивостоке —
-- разные моменты UTC.
--
-- Почему чистый SQL, а не Edge Function: в отличие от generate-upcoming и
-- send-reminders здесь нечего считать вне БД — ни HTTP, ни VAPID, ни секретов.
-- Одного UPDATE достаточно, и он не может упасть по сети.
--
-- ВАЖНО — 'missed' НЕ терминальный статус. Юзер в любой момент может открыть
-- пропущенный слот и отметить «принято, вот когда»: карточка любого не-upcoming
-- слота открывает backfill-диалог (components/tracker/slot-card.tsx), диалог
-- берёт день из scheduled_at слота (не из «сегодня»), а server action
-- backfillTaken (lib/tracker/intake.ts) запрещает только БУДУЩЕЕ время —
-- насколько давно был приём, ему всё равно. Этот UPDATE ничего в той цепочке
-- не ломает: он меняет только status, не трогая taken_at.
--
-- ----------------------------------------------------------------------------
-- КАК ПРИМЕНИТЬ (Supabase CLI не настроен — накатываем руками)
-- ----------------------------------------------------------------------------
-- 1. Supabase Dashboard → SQL Editor → New query.
-- 2. Вставить весь файл целиком → Run. Плейсхолдеров здесь НЕТ, в отличие от
--    20260612130000_etap1b_cron_jobs.sql — заменять ничего не нужно.
-- 3. Последним стейтментом идёт разовый прогон по накопленному. Он вернёт
--    число помеченных слотов — это и есть проверка, что всё сработало.
-- 4. Убедиться, что джоб встал:
--       select jobid, jobname, schedule, active from cron.job;
--    Ожидаем строку 'mark-missed-intakes-every-15-min' со schedule '*/15 * * * *'.
--
-- Идемпотентность: create or replace function + cron.unschedule перед
-- cron.schedule. Файл можно прогнать повторно без ошибок. Разовый UPDATE в
-- конце тоже идемпотентен — второй прогон пометит 0 рядов.
--
-- Откат:
--   select cron.unschedule('mark-missed-intakes-every-15-min');
--   drop function if exists public.mark_missed_intakes();
-- Уже проставленные 'missed' при этом останутся — вернуть их в 'upcoming'
-- можно вручную, но осмысленной причины нет.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. Функция развёртки
-- ----------------------------------------------------------------------------
-- Возвращает число помеченных рядов — удобно и для разового прогона ниже,
-- и чтобы руками проверить работу джоба (select public.mark_missed_intakes()).
--
-- НЕ security definer, сознательно. Функция обходит RLS только потому, что
-- pg_cron исполняет её от владельца таблиц (postgres). Сделай её security
-- definer — и любой authenticated-юзер смог бы одним вызовом переписать
-- статусы ЧУЖИХ приёмов. Права на execute отзываются ниже отдельно.

create or replace function public.mark_missed_intakes()
returns integer
language plpgsql
as $$
declare
  affected integer;
begin
  update public.intake_events e
  set status = 'missed'
  from public.profiles p
  where e.user_id = p.id
    and e.status = 'upcoming'

    -- Страховка, а не оптимизация: будущий слот пометить missed нельзя
    -- ни при каких данных в profiles.timezone. Условие ниже это и так
    -- гарантирует (день слота строго меньше сегодняшнего ⇒ слот в прошлом),
    -- но явная проверка дешевле разбирательства, если tz окажется мусором.
    and e.scheduled_at < now()

    -- Битая tz уронила бы `at time zone` с invalid_parameter_value и весь
    -- UPDATE вместе с ним — из-за одного ряда джоб перестал бы работать для
    -- всех. Значения в profiles.timezone валидируются на записи
    -- (lib/timezone.ts, isValidIanaTimezone), так что это защита от того,
    -- чего быть не должно; цена — семи-джойн по ~1200 строкам каталога.
    and p.timezone in (select name from pg_timezone_names)

    -- Собственно правило: календарный день слота в tz юзера СТРОГО раньше
    -- сегодняшнего дня в той же tz. `timestamptz at time zone 'X'` даёт
    -- wall-clock в этой зоне, ::date отрезает время.
    and (e.scheduled_at at time zone p.timezone)::date
        < (now() at time zone p.timezone)::date;

  get diagnostics affected = row_count;
  return affected;
end;
$$;

-- По умолчанию Postgres выдаёт execute на функции роли PUBLIC. Здесь это
-- означало бы, что клиент с anon/authenticated-ключом может дёрнуть развёртку
-- через PostgREST. Сама по себе она чужие данные не раскрывает (и RLS от
-- имени authenticated отфильтрует ряды), но вызывать её юзеру незачем.
revoke execute on function public.mark_missed_intakes() from public;


-- ----------------------------------------------------------------------------
-- 2. Cron-джоб: каждые 15 минут
-- ----------------------------------------------------------------------------
-- Почему 15, а не раз в час: переход «день юзера кончился» происходит в его
-- полночь, и смещения зон бывают не только целочасовые (+05:30 Индия,
-- +05:45 Непал). Шаг 15 минут накрывает все существующие смещения, так что
-- слот становится missed максимум через четверть часа после полуночи юзера.
--
-- pg_cron и pg_net уже включены миграцией 20260612130000_etap1b_cron_jobs.sql.
-- В отличие от тамошних джобов, этот НЕ ходит по HTTP — ни pg_net, ни Vault,
-- ни CRON_SECRET ему не нужны.
--
-- Отдельным файлом, а не дописыванием в etap1b_cron_jobs.sql: тот уже накачен,
-- и повторный прогон упал бы на vault.create_secret с дублем имени секрета.

select cron.unschedule('mark-missed-intakes-every-15-min')
where exists (
  select 1 from cron.job where jobname = 'mark-missed-intakes-every-15-min'
);

select cron.schedule(
  'mark-missed-intakes-every-15-min',
  '*/15 * * * *',
  $$ select public.mark_missed_intakes(); $$
);


-- ----------------------------------------------------------------------------
-- 3. Разовый прогон по накопленному
-- ----------------------------------------------------------------------------
-- Решение 2026-08-03: помечаем ВСЁ накопленное, отсечки по дате не делаем —
-- данных мало и они свежие. Если бы база была старой, стоило бы подумать:
-- слот, который юзер на самом деле принял, но не отметил, станет «пропущено»
-- и занизит регулярность. Здесь этим можно пренебречь, а точечно поправить
-- всегда можно через backfill в самом приложении.
--
-- Возвращает число помеченных слотов.

select public.mark_missed_intakes() as marked_missed;
