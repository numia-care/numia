-- ----------------------------------------------------------------------------
-- 1. Констрейнты и колонки-копии
-- ----------------------------------------------------------------------------

alter table public.lab_results
  drop constraint if exists lab_numeric_or_photo,
  drop constraint if exists lab_numeric_well_formed,
  drop constraint if exists blank_photo_path_iv_together,
  drop column if exists measured_at,
  drop column if exists note_ciphertext,
  drop column if exists blank_photo_path,
  drop column if exists blank_photo_iv;


-- ----------------------------------------------------------------------------
-- 2. Строка = показатель со значением, иначе никак
-- ----------------------------------------------------------------------------

alter table public.lab_results
  alter column analyte set not null,
  alter column value set not null,
  alter column unit set not null;
