-- (миграции 20260526/20260613: GRANT ... ON public.profiles), а табличный
-- GRANT автоматически покрывает колонки, добавленные позже. RLS-политики
-- profiles_select_own / profiles_update_own тоже действуют на всю строку,
-- включая новую колонку — юзер читает/пишет соль только в своём профиле.
