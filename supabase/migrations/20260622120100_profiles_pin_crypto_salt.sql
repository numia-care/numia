-- ============================================================================
-- profiles.pin_crypto_salt — соль деривации E2E-ключа переезжает на сервер
-- ============================================================================
--
-- Контекст (зафиксировано 2026-06-22, Вариант 1). До сих пор соль для
-- деривации crypto-ключа (PBKDF2 → AES-GCM, lib/crypto/key.ts) жила ТОЛЬКО в
-- IndexedDB на устройстве (lib/crypto/storage.ts, ключ pin_crypto_salt). Это
-- значило: один и тот же PIN на двух устройствах давал РАЗНЫЕ ключи → E2E-
-- контент, зашифрованный на устройстве A, не читался на устройстве B.
--
-- Для фичи «Путь» (наша первая E2E-фича) это блокер: фото/заметки должны
-- расшифровываться с любого устройства юзера. Поэтому crypto-соль становится
-- server-side — в profiles.
--
-- ВАЖНО: переезжает только СROPTO-соль (деривация ключа). Соль и хэш
-- ВЕРИФИКАЦИИ PIN (pin_salt/pin_hash, lib/crypto/pin.ts) остаются device-local
-- в IndexedDB — это «правильный ли PIN ввели на этом устройстве», серверу не
-- нужно. Разные домены (разные info-теги в деривации) — не путать.
--
-- Почему server-side соль безопасна (E2E сохраняется):
--   • Соль PBKDF2 — НЕ секрет. Её задача — чтобы одинаковый PIN давал
--     одинаковый ключ и чтобы радужные таблицы не переиспользовались между
--     юзерами. Сама по себе она ключ не раскрывает.
--   • Сервер хранит соль, но НЕ хранит PIN. Без PIN ключ из соли не вывести.
--     Значит ни Supabase, ни команда расшифровать контент не могут — граница
--     E2E на месте.
--   • Сброс PIN затирает соль (см. план в CLAUDE.md): старый E2E-контент
--     становится нечитаем навсегда. By design, юзер предупреждён.
--
-- Как применить:
-- Supabase Dashboard → SQL Editor → New query → вставить → Run.
-- ============================================================================

-- nullable: у юзера может ещё не быть PIN (соль появляется при установке PIN).
-- if not exists — миграция идемпотентна (в отличие от CREATE TABLE).
alter table public.profiles
  add column if not exists pin_crypto_salt text;

