-- ============================================================================
-- Privacy-аудит 2026-08-02: зачистка собранных User-Agent
-- ============================================================================
--
-- ЧТО И ПОЧЕМУ
--
-- push_subscriptions.user_agent собирался полной сырой строкой под экран
-- устройств в /settings («iPhone PWA», «Chrome on Mac» + отзыв подписки с
-- конкретного телефона). Экран так и не был сделан, поле не читал никто —
-- данные копились впустую.
--
-- Цена была высокой: полная строка UA — это модель устройства, версия ОС и
-- браузера, признак PWA. Рядом лежит user_id → FK на auth.users → email.
-- То есть в базе хранилась прямая связка «email ↔ конкретное устройство» —
-- самое чувствительное сочетание для нашей модели угроз (CLAUDE.md:
-- государства с трансфобной политикой, семья с доступом к телефону,
-- утечка базы).
--
-- Запись уже убрана из кода (lib/push/actions.ts) — новые подписки UA не
-- пишут. Эта миграция затирает то, что успело накопиться.
--
-- КОЛОНКУ НЕ УДАЛЯЕМ, а обнуляем. Причины:
--   1. DROP COLUMN на живой таблице сломал бы работающие поды, которые ещё
--      крутят старый бандл со вставкой user_agent (деплой Vercel и накат
--      миграции не атомарны).
--   2. Данные исчезают одинаково при обоих вариантах — цель достигнута.
-- Саму колонку снимем отдельной миграцией, когда новый код доедет везде.
--
-- Идемпотентна: повторный запуск просто ничего не найдёт.
-- ============================================================================

update public.push_subscriptions
set user_agent = null
where user_agent is not null;

-- Страховка от возврата: если поле снова начнут писать, значение отсечётся
-- на уровне БД, а не будет молча копиться до следующего аудита.
alter table public.push_subscriptions
  add constraint push_subscriptions_no_user_agent
  check (user_agent is null);
